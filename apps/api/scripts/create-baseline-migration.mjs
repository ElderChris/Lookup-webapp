// =============================================================================
// apps/api/scripts/create-baseline-migration.mjs
// =============================================================================
// Genera la migrazione iniziale Prisma (prisma/migrations/0_init) a partire da
// schema.prisma, senza bisogno di un database.
//
// Uso (una sola volta, poi committare la cartella prisma/migrations):
//   npm run db:baseline -w apps/api
//
// Scrive i file in UTF-8 senza BOM, indipendentemente dalla shell (in
// Windows PowerShell 5.1 la redirezione `>` produrrebbe UTF-16).
// Non sovrascrive una migrazione gia' esistente.
// =============================================================================
import { spawnSync } from 'node:child_process';
import { existsSync, mkdirSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const API_ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const MIGRATIONS = path.join(API_ROOT, 'prisma', 'migrations');
const INIT_DIR = path.join(MIGRATIONS, '0_init');
const INIT_SQL = path.join(INIT_DIR, 'migration.sql');
const LOCK = path.join(MIGRATIONS, 'migration_lock.toml');

if (existsSync(INIT_SQL)) {
  console.error(`[baseline] ${path.relative(API_ROOT, INIT_SQL)} esiste gia': nessuna modifica.`);
  process.exit(1);
}

const res = spawnSync(
  'npx',
  [
    'prisma',
    'migrate',
    'diff',
    '--from-empty',
    '--to-schema-datamodel',
    'prisma/schema.prisma',
    '--script',
  ],
  { cwd: API_ROOT, encoding: 'utf8', shell: true, maxBuffer: 32 * 1024 * 1024 }
);
if (res.status !== 0 || !res.stdout.includes('CREATE TABLE')) {
  console.error('[baseline] prisma migrate diff fallito:');
  console.error(res.stderr || res.stdout);
  process.exit(1);
}

mkdirSync(INIT_DIR, { recursive: true });
writeFileSync(INIT_SQL, res.stdout, 'utf8');
if (!existsSync(LOCK)) {
  writeFileSync(
    LOCK,
    '# Please do not edit this file manually\n# It should be added in your version-control system (i.e. Git)\nprovider = "postgresql"\n',
    'utf8'
  );
}

const tables = (res.stdout.match(/CREATE TABLE/g) || []).length;
console.log(`[baseline] creata ${path.relative(API_ROOT, INIT_SQL)} (${tables} tabelle).`);
